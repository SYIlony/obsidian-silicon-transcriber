function buildMultipartBody(fields, boundary) {
  const parts = [];
  const CRLF = "\r\n";
  for (const field of fields) {
    parts.push(Buffer.from(`--${boundary}${CRLF}`));
    if (typeof field.value === "string") {
      parts.push(Buffer.from(
        `Content-Disposition: form-data; name="${field.name}"${CRLF}${CRLF}`
      ));
      parts.push(Buffer.from(field.value));
      parts.push(Buffer.from(CRLF));
    } else {
      const { buffer, filename } = field.value;
      parts.push(Buffer.from(
        `Content-Disposition: form-data; name="${field.name}"; filename="${filename}"${CRLF}Content-Type: audio/mpeg${CRLF}${CRLF}`
      ));
      parts.push(buffer);
      parts.push(Buffer.from(CRLF));
    }
  }
  parts.push(Buffer.from(`--${boundary}--${CRLF}`));
  return Buffer.concat(parts);
}
